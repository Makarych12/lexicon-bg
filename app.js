  /* ---------- Двигател на последователностите ---------- */
  var ANIM = {
    timeouts: [],
    intervals: [],
    done: null,
    running: false,
    duration: 0,

    clear: function () {
      this.timeouts.forEach(function (t) { clearTimeout(t); });
      this.timeouts = [];
      this.intervals.forEach(function (t) { clearInterval(t); });
      this.intervals = [];
      if (this.done) { clearTimeout(this.done); this.done = null; }
      this.running = false;
    },

    fire: function (evt) {
      var id = evt[1], type = evt[2];
      var el = svgHost.querySelector('#' + id);
      if (!el) return;
      var self = this;
      switch (type) {
        case 'wire':
          /* Growing wire: animate from origin to end, then switch to persistent flow */
          el.classList.remove('fading');
          el.classList.add('growing');
          var wnum = el.getAttribute('data-wire');
          if (wnum) {
            svgHost.querySelectorAll('.wirenum[data-wire="' + wnum + '"]').forEach(function (t) {
              t.classList.add('on');
            });
          }
          /* After grow animation completes, switch to persistent flow state */
          (function (wireEl) {
            self.timeouts.push(setTimeout(function () {
              wireEl.classList.remove('growing');
              wireEl.classList.add('grown');
              /* After a brief persistent flow, settle into active state */
              self.timeouts.push(setTimeout(function () {
                wireEl.classList.remove('grown');
                wireEl.classList.add('active');
              }, 300));
            }, 500));
          })(el);
          break;
        case 'contact':
          el.classList.add('closed');
          break;
        case 'contact-open':
          el.classList.remove('closed');
          break;
        case 'coil':
          el.classList.add('on');
          el.querySelectorAll('.coilwind').forEach(function (w) { w.classList.add('on'); });
          break;
        case 'coil-off':
          el.classList.remove('on');
          el.querySelectorAll('.coilwind').forEach(function (w) { w.classList.remove('on'); });
          break;
        case 'device':
          el.classList.add('on');
          break;
        case 'device-off':
          el.classList.remove('on');
          break;
        case 'motor':
          el.classList.add('on');
          el.classList.add('running');
          /* Show RPM label with animated count-up */
          var rpmEl = svgHost.querySelector('#rpm-' + id.replace('dev-', ''));
          if (rpmEl) {
            rpmEl.setAttribute('opacity', '1');
            var targetRpm = id === 'dev-СтГ' ? 250 : 1500;
            var curRpm = 0;
            (function (label, target) {
              var interval = setInterval(function () {
                curRpm += Math.max(10, Math.floor((target - curRpm) * 0.15));
                if (curRpm >= target) { curRpm = target; clearInterval(interval); }
                label.textContent = curRpm + ' об/мин';
              }, 50);
              self.intervals.push(interval);
            })(rpmEl, targetRpm);
          }
          break;
        case 'motor-off':
          el.classList.remove('running');
          var rpmOff = svgHost.querySelector('#rpm-' + id.replace('dev-', ''));
          if (rpmOff) {
            rpmOff.setAttribute('opacity', '0');
            rpmOff.textContent = '0 об/мин';
          }
          break;
        case 'press':
          el.classList.add('pressed');
          break;
        case 'release':
          el.classList.remove('pressed');
          break;
      }
    },

    play: function (step, cb) {
      this.clear();
      var seq = SEQUENCES[step];
      if (!seq || seq.length === 0) {
        this.duration = 0;
        if (cb) cb();
        return;
      }
      this.running = true;
      var self = this;
      var maxDelay = 0;
      seq.forEach(function (evt) {
        if (evt[0] > maxDelay) maxDelay = evt[0];
        self.timeouts.push(setTimeout(function () { self.fire(evt); }, evt[0]));
      });
      /* Schedule text line highlights synchronized with animation */
      var s = STEPS[step];
      if (s && Array.isArray(s.text)) {
        s.text.forEach(function (line, idx) {
          self.timeouts.push(setTimeout(function () {
            highlightTextLine(idx);
          }, line.delay));
        });
        /* Clear highlight after animation completes */
        self.timeouts.push(setTimeout(function () {
          clearTextHighlight();
        }, maxDelay + 200));
      }
      this.duration = maxDelay;
      this.done = setTimeout(function () {
        self.running = false;
        if (cb) cb();
      }, maxDelay + 160);
    }
  };

