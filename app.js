  function zoomAt(cx, cy, factor) {
    var k = view.k * factor;
    k = Math.max(0.3, Math.min(4.5, k));
    var hostRect = svgHost.getBoundingClientRect();
    var px = cx - hostRect.left;
    var py = cy - hostRect.top;
    view.x = px - (px - view.x) * (k / view.k);
    view.y = py - (py - view.y) * (k / view.k);
    view.k = k;
    applyView();
  }

  function resetView() {
    var host = svgHost;
    var w = host.clientWidth || 900;
    var h = host.clientHeight || 700;
    var k = Math.min(w / 1400, h / 920) * 0.97;
    k = Math.max(0.72, k);
    view.k = k;
    view.x = (w - 1400 * view.k) / 2;
    view.y = (h - 920 * view.k) / 2;
    setSmooth(true);
    applyView();
    if (smoothTimer) clearTimeout(smoothTimer);
    smoothTimer = setTimeout(function () { setSmooth(false); }, 420);
  }

