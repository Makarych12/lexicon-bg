  function setStep(n, force) {
    n = Math.max(0, Math.min(STEPS.length - 1, n));
    var prev = lastStep;
    STEP = n;
    lastStep = n;

    var s = STEPS[STEP];
    stepLabel.textContent = lang(s.title);
    stepProgress.style.width = ((STEP + 1) / STEPS.length * 100) + '%';
    drawerTitle.textContent = lang(s.title);
    renderStepText(s);
    btnPrev.disabled = STEP === 0;
    btnNext.disabled = STEP === STEPS.length - 1;

    ANIM.clear();
    stopTimer();
    clearTimeout(PLAY_TIMER);
    PLAY_TIMER = null;

    if (STEP === 2) startTimer();

    var prevState = prev !== null ? STEP_STATE[prev] : { wires: [], contacts: [], coils: [], devices: [], motors: [] };
    var curState = STEP_STATE[STEP] || prevState;

    turnOffDiff(prevState, curState);
    applyBase();

    var isForward = prev === null || STEP > prev || force;

    function after() {
      reconcileAdd(curState);
      updateContactsInCard();
      if (PLAYING) scheduleNext();
    }

    if (isForward) {
      ANIM.play(STEP, after);
    } else {
      reconcileAdd(curState);
      after();
    }
  }

